// Command mcpgen generates the catalog's MCP tool table from the OpenAPI document: every
// operation tagged `x-mcp` becomes one tool whose handler calls the generated strict server
// interface in process. Run through `make generate`.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"os"
	"sort"
	"strings"

	"github.com/getkin/kin-openapi/openapi3"
)

type param struct {
	Name     string // wire name
	Field    string // Go field name
	GoType   string
	Required bool
	In       string
}

type tool struct {
	Name        string
	Description string
	ReadOnly    bool
	Destructive *bool
	Idempotent  bool
	Method      string // Go method on StrictServerInterface
	Path        []param
	Query       []param
	HasParams   bool // whether a <Op>Params struct exists (query params present)
	BodyModel   string
	InputType   string
}

func main() {
	spec := flag.String("spec", "", "OpenAPI document")
	out := flag.String("out", "", "output Go file")
	pkg := flag.String("pkg", "mcp", "package name")
	flag.Parse()
	if *spec == "" || *out == "" {
		fmt.Fprintln(os.Stderr, "usage: mcpgen -spec openapi.yaml -out tools.gen.go")
		os.Exit(2)
	}
	loader := openapi3.NewLoader()
	doc, err := loader.LoadFromFile(*spec)
	if err != nil {
		fail(err)
	}
	var tools []tool
	for _, path := range sortedPaths(doc) {
		item := doc.Paths.Find(path)
		for method, op := range item.Operations() {
			raw, ok := op.Extensions["x-mcp"]
			if !ok {
				continue
			}
			ext, ok := raw.(map[string]any)
			if !ok {
				fail(fmt.Errorf("%s %s: x-mcp must be an object", method, path))
			}
			t := tool{Name: str(ext["tool"]), Description: str(ext["description"]), Method: goName(op.OperationID)}
			if v, ok := ext["readOnlyHint"].(bool); ok {
				t.ReadOnly = v
			}
			if v, ok := ext["destructiveHint"].(bool); ok {
				t.Destructive = &v
			}
			if v, ok := ext["idempotentHint"].(bool); ok {
				t.Idempotent = v
			}
			for _, pref := range op.Parameters {
				p := pref.Value
				gp := param{Name: p.Name, Field: fieldName(p.Name), GoType: goType(p.Schema, p.Required), Required: p.Required, In: p.In}
				switch p.In {
				case "path":
					t.Path = append(t.Path, gp)
				case "query":
					t.Query = append(t.Query, gp)
				}
			}
			t.HasParams = len(t.Query) > 0
			if op.RequestBody != nil && op.RequestBody.Value != nil {
				if mt := op.RequestBody.Value.Content.Get("application/json"); mt != nil && mt.Schema != nil && mt.Schema.Ref != "" {
					t.BodyModel = refName(mt.Schema.Ref)
				}
			}
			t.InputType = lowerFirst(goName(op.OperationID)) + "Input"
			tools = append(tools, t)
		}
	}
	sort.Slice(tools, func(i, j int) bool { return tools[i].Name < tools[j].Name })
	src := render(*pkg, tools)
	formatted, err := format.Source(src)
	if err != nil {
		_ = os.WriteFile(*out, src, 0o644)
		fail(fmt.Errorf("format: %w (unformatted output written)", err))
	}
	if err := os.WriteFile(*out, formatted, 0o644); err != nil {
		fail(err)
	}
	fmt.Printf("wrote %s: %d tools\n", *out, len(tools))
}

func render(pkg string, tools []tool) []byte {
	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by cmd/mcpgen from the OpenAPI document. DO NOT EDIT.\n\npackage %s\n\n", pkg)
	b.WriteString("import (\n\t\"context\"\n\n\tsdk \"github.com/modelcontextprotocol/go-sdk/mcp\"\n\n\t\"github.com/apache/texera/catalog/internal/api\"\n)\n\n")
	for _, t := range tools {
		fmt.Fprintf(&b, "// %s is the input of the %s tool.\ntype %s struct {\n", t.InputType, t.Name, t.InputType)
		for _, p := range t.Path {
			fmt.Fprintf(&b, "\t%s %s `json:\"%s\"`\n", p.Field, p.GoType, p.Name)
		}
		for _, p := range t.Query {
			fmt.Fprintf(&b, "\t%s %s `json:\"%s,omitempty\"`\n", p.Field, p.GoType, p.Name)
		}
		if t.BodyModel != "" {
			fmt.Fprintf(&b, "\tapi.%s\n", t.BodyModel)
		}
		b.WriteString("}\n\n")
	}
	b.WriteString("// registerTools adds every x-mcp operation as a tool. wrap derives the handler context from\n// the MCP request (it carries the caller); finish renders the strict response.\n")
	b.WriteString("func registerTools(s *sdk.Server, impl api.StrictServerInterface, wrap func(context.Context, *sdk.CallToolRequest) (context.Context, error), finish func(any, error) (*sdk.CallToolResult, map[string]any, error)) {\n")
	for _, t := range tools {
		fmt.Fprintf(&b, "\tsdk.AddTool(s, &sdk.Tool{Name: %q, Description: %q, Annotations: &sdk.ToolAnnotations{ReadOnlyHint: %v, IdempotentHint: %v", t.Name, t.Description, t.ReadOnly, t.Idempotent)
		if t.Destructive != nil {
			fmt.Fprintf(&b, ", DestructiveHint: boolPtr(%v)", *t.Destructive)
		}
		fmt.Fprintf(&b, "}}, func(ctx context.Context, req *sdk.CallToolRequest, in %s) (*sdk.CallToolResult, map[string]any, error) {\n", t.InputType)
		b.WriteString("\t\tctx, err := wrap(ctx, req)\n\t\tif err != nil {\n\t\t\treturn finish(nil, err)\n\t\t}\n")
		fmt.Fprintf(&b, "\t\tresp, err := impl.%s(ctx, api.%sRequestObject{", t.Method, t.Method)
		var fields []string
		for _, p := range t.Path {
			fields = append(fields, fmt.Sprintf("%s: in.%s", p.Field, p.Field))
		}
		if t.HasParams {
			var qf []string
			for _, p := range t.Query {
				qf = append(qf, fmt.Sprintf("%s: in.%s", p.Field, p.Field))
			}
			fields = append(fields, fmt.Sprintf("Params: api.%sParams{%s}", t.Method, strings.Join(qf, ", ")))
		}
		if t.BodyModel != "" {
			fields = append(fields, fmt.Sprintf("Body: &in.%s", t.BodyModel))
		}
		b.WriteString(strings.Join(fields, ", "))
		b.WriteString("})\n\t\treturn finish(resp, err)\n\t})\n")
	}
	b.WriteString("}\n\nfunc boolPtr(b bool) *bool { return &b }\n")
	return b.Bytes()
}

func sortedPaths(doc *openapi3.T) []string {
	var out []string
	for p := range doc.Paths.Map() {
		out = append(out, p)
	}
	sort.Strings(out)
	return out
}

func str(v any) string {
	s, _ := v.(string)
	return s
}

// goName mirrors oapi-codegen's operation naming: Workflows_run -> WorkflowsRun.
func goName(operationID string) string {
	parts := strings.FieldsFunc(operationID, func(r rune) bool { return r == '_' || r == '-' || r == ' ' })
	var b strings.Builder
	for _, p := range parts {
		b.WriteString(strings.ToUpper(p[:1]) + p[1:])
	}
	return b.String()
}

func fieldName(name string) string {
	return strings.ToUpper(name[:1]) + name[1:]
}

func lowerFirst(s string) string {
	return strings.ToLower(s[:1]) + s[1:]
}

func refName(ref string) string {
	i := strings.LastIndex(ref, "/")
	return ref[i+1:]
}

func goType(ref *openapi3.SchemaRef, required bool) string {
	var t string
	switch {
	case ref == nil:
		t = "string"
	case ref.Ref != "":
		t = "api." + refName(ref.Ref)
	default:
		typ := ""
		if ref.Value != nil && ref.Value.Type != nil {
			types := ref.Value.Type.Slice()
			if len(types) > 0 {
				typ = types[0]
			}
		}
		switch typ {
		case "integer":
			if ref.Value.Format == "int64" {
				t = "int64"
			} else {
				t = "int32"
			}
		case "number":
			t = "float64"
		case "boolean":
			t = "bool"
		default:
			t = "string"
		}
	}
	if !required {
		return "*" + t
	}
	return t
}

func fail(err error) {
	fmt.Fprintln(os.Stderr, "mcpgen:", err)
	os.Exit(1)
}
